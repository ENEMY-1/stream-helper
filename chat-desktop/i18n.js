function normalizeLanguage(value) {
  const lang = String(value == null ? '' : value).trim().toLowerCase();
  if (lang === 'ru' || lang === 'en') return lang;
  return 'auto';
}

function getBrowserLang() {
  if (typeof navigator === 'undefined') return 'ru';
  const lang = navigator.language || navigator.userLanguage || 'ru';
  return String(lang).toLowerCase().indexOf('ru') === 0 ? 'ru' : 'en';
}

function resolveLanguage(value) {
  const lang = normalizeLanguage(value);
  if (lang === 'auto') return getBrowserLang();
  return lang;
}

function getLocale(lang) {
  return LOCALES[resolveLanguage(lang)] || LOCALES.ru;
}

